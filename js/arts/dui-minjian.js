  function castByNums(a, b) {
    const upper = numToGua(a);
    const lower = numToGua(b);
    const lines = lower.lines.concat(upper.lines);
    const hex = C.HEX64[lines.join('')];
    const dong = (((a + b) % 6) + 6) % 6;
    const dongLines = [dong];
    const bian = C.bianGua(lines, dongLines);
    const ti = dong <= 2 ? upper : lower;          /* 动爻在下卦则上卦为体，反之亦然 */
    const yong = dong <= 2 ? lower : upper;
    const rel = C.wxRelation(ti.wx, yong.wx);
    return { a, b, upper, lower, hex, bian, dong, ti, yong, rel, yongLines: lines };
  }

