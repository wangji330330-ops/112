/* ============================================================
   艮 · 河洛理数
   以八字化卦：天干配河图数（通行口诀），地支配洛书宫数（或口诀支数），
   天干之数合为「天数」、地支之数合为「地数」，
   依「天数二十五、地数三十」取余定卦，得先天卦与后天卦。
   所用口诀与取卦规则全文写在页面上；异说与简化处逐一注明。
   ============================================================ */
(function () {
  'use strict';
  const C = window.CORE, U = C.UI, G = C.GZ;
  const ART = window.ART;

  function hashStr(s) {
    let h = 2166136261 >>> 0;
    s = String(s === undefined || s === null ? '' : s);
    for (let i = 0; i < s.length; i++) {
      h ^= s.charCodeAt(i);
      h = Math.imul(h, 16777619) >>> 0;
    }
    return h >>> 0;
  }

  /* ---------- 一、配数 ---------- */
  /* 通行口诀：甲己子午九、乙庚丑未八、丙辛寅申七、丁壬卯酉六、戊癸辰戌五、巳亥四。
     此口诀兼摄干支：干与支同数。 */
  const GAN_NUM = { 甲: 9, 乙: 8, 丙: 7, 丁: 6, 戊: 5, 己: 9, 庚: 8, 辛: 7, 壬: 6, 癸: 5 };
  const ZHI_NUM_KOUJUE = { 子: 9, 丑: 8, 寅: 7, 卯: 6, 辰: 5, 巳: 4, 午: 9, 未: 8, 申: 7, 酉: 6, 戌: 5, 亥: 4 };
  /* 洛书宫数（地支归后天八卦之宫）：子坎一、丑寅艮八、卯震三、辰巳巽四、
     午离九、未申坤二、酉兑七、戌亥乾六。取自本站核心之地支—宫数表。 */
  const ZHI_NUM_LUOSHU = (function () {
    const m = {};
    C.ZHI.forEach(function (z, i) { m[z] = C.ZHI_GONG[i]; });
    return m;
  })();

  /* ---------- 二、八卦之数 ---------- */
  /* 先天八卦数：乾一 兑二 离三 震四 巽五 坎六 艮七 坤八（见 C.XIANTIAN 之序） */
  const XIANTIAN_NUM = C.XIANTIAN.slice();
  /* 后天（洛书）八卦数：坎一 坤二 震三 巽四 中五 乾六 兑七 艮八 离九。
     中五无卦，本站从遁甲、八宅通例寄坤二宫。 */
  const HOUTIAN_NUM = ['kan', 'kun', 'zhen', 'xun', 'kun', 'qian', 'dui', 'gen', 'li'];

  const GAN_POS = ['年干', '月干', '日干', '时干'];
  const ZHI_POS = ['年支', '月支', '日支', '时支'];

  ART({
    id: 'heluo',
    name: '河洛理数',
    alias: ['河洛数', '河洛化卦'],
    gua: 'gen',
    order: 4,
    tagline: '八字化卦 · 以干支配河洛之数，天数二十五、地数三十取余，得先后天之卦',

    intro: `
      <p>河洛理数为旧题宋·陈抟（希夷）所传之术，明清间有刻本行世（作者与成书年代古今有异说，本站不深考）。其法：以人之八字四柱干支配河图、洛书之数，天干所得之数合为「天数」，地支所得之数合为「地数」，再依「天数二十五、地数三十」取其余数而定卦，遂得先天卦与后天卦，以观其体用。</p>
      <p>其理本于河图、洛书之数。河图之数以五行生成相配（一六水、二七火、三八木、四九金、五十土），洛书之数布于九宫（戴九履一、左三右七、二四为肩、六八为足）。人禀天地之气而生于某年某月某日某时，其干支即其禀气之标记；以干支之数观气之厚薄多寡，以卦象观气之体用趋向，这就是河洛化卦的思路。</p>
      <p>它与四柱八字同以干支为骨，但取径不同：八字讲十神、旺衰、格局、喜忌，仍以干支本身论事；河洛则一路化数为卦，最后落在六十四卦的卦象上，可说是「命理」与「卦理」之间的一座桥。本站所存者为配数与取卦的规则本身，其白话断语为参考性解读，非原书断法。</p>`,

    method: `
      <p>填入出生（或起课）的时刻，按「化卦」即见：四柱干支与逐柱的配数、天数与地数之和及其取余、先天卦（体）与后天卦（用）的卦象，以及白话解读。</p>
      <p>「地支之数」有异说，可择其一：<b>甲说</b>取洛书宫数（子坎一、丑寅艮八……即地支所属之后天八卦宫数），<b>乙说</b>取通行口诀之支数（子午九、丑未八……）。天干之数两说皆用通行口诀之干数。所问可留空。同一个时刻必得同一卦，可自行复核。</p>`,

    form: [
      { name: 'dt', label: '出生 / 起课时刻', type: 'datetime-local', value: U.nowStr(), wide: true, hint: '以此刻之四柱干支化卦（按本机本地时间取干支）' },
      { name: 'q', label: '所问之事', type: 'text', placeholder: '如「此番谋事之体用何如」，可留空' },
      { name: 'zhiNum', label: '地支之数', type: 'select', value: 'luoshu', options: [
        { v: 'luoshu', t: '甲说 · 洛书宫数（子一 丑八 寅八 卯三 …）' },
        { v: 'koujue', t: '乙说 · 口诀支数（子午九 丑未八 …）' }
      ] }
    ],

    /* ★ 纯函数：只读 input，不碰 DOM */
    cast: function (input) {
      const dt = (input.dt || '').trim();
      if (!dt) return { error: '请填写出生或起课时刻' };
      const q = (input.q || '').trim();
      const zhiWay = input.zhiNum === 'koujue' ? 'koujue' : 'luoshu';
      const zhiNum = zhiWay === 'koujue' ? ZHI_NUM_KOUJUE : ZHI_NUM_LUOSHU;

      const fp = G.fourPillars(U.parseDT(dt));
      const gans = [fp.year.gan, fp.month.gan, fp.day.gan, fp.hour.gan];
      const zhis = [fp.year.zhi, fp.month.zhi, fp.day.zhi, fp.hour.zhi];

      /* 逐柱配数 */
      const rows = [0, 1, 2, 3].map(function (i) {
        const g = gans[i], z = zhis[i];
        return {
          pos: ['年柱', '月柱', '日柱', '时柱'][i],
          gz: g + z, gan: g, ganNum: GAN_NUM[g], zhi: z, zhiNum: zhiNum[z]
        };
      });

      /* 天数（四干之数之和）、地数（四支之数之和） */
      let D = 0, E = 0;
      rows.forEach(function (r) { D += r.ganNum; E += r.zhiNum; });

      /* 天数二十五、地数三十：取其余数，余零则用其全数 */
      let d = D % 25; if (d === 0) d = 25;
      let e = E % 30; if (e === 0) e = 30;

      /* 先天卦：先天八卦数定上下卦（天数为上、地数为下） */
      const upX = C.GUA_BY_ID[XIANTIAN_NUM[(d - 1) % 8]];
      const loX = C.GUA_BY_ID[XIANTIAN_NUM[(e - 1) % 8]];
      const hexX = C.HEX64[loX.lines.concat(upX.lines).join('')];

      /* 后天卦：后天（洛书）八卦数定上下卦 */
      const upH = C.GUA_BY_ID[HOUTIAN_NUM[((d - 1) % 9)]];
      const loH = C.GUA_BY_ID[HOUTIAN_NUM[((e - 1) % 9)]];
      const hexH = C.HEX64[loH.lines.concat(upH.lines).join('')];

      /* 白话参断所需之比量 */
      const yingTian = D > 25 ? '盈' : (D < 25 ? '不足' : '恰合');
      const yingDi = E > 30 ? '盈' : (E < 30 ? '不足' : '恰合');
      const duoGua = D > E ? 'tian' : (E > D ? 'di' : 'ping');

      return {
        dt: dt, q: q, zhiWay: zhiWay, zhiWayName: zhiWay === 'koujue' ? '口诀支数（子午九、丑未八……）' : '洛书宫数（子一、丑八、寅八……）',
        fpText: fp.year.name + '年 ' + fp.month.name + '月 ' + fp.day.name + '日 ' + fp.hour.name + '时',
        gans: gans, zhis: zhis, rows: rows,
        D: D, E: E, d: d, e: e,
        upX: upX.name, loX: loX.name, hexX: hexX,
        upH: upH.name, loH: loH.name, hexH: hexH,
        yingTian: yingTian, yingDi: yingDi, duoGua: duoGua, jieqi: fp.jieqi,
        seed: hashStr(dt + '|' + q + '|' + zhiWay)
      };
    },

    /* ★ 纯函数：返回 HTML 字符串 */
    view: function (d) {
      const out = [];

      out.push(U.resHead('先天 ' + d.hexX.name + ' · 后天 ' + d.hexH.name,
        '河洛理数 · ' + d.fpText + ' · ' + d.dt));

      /* 四柱与配数 */
      out.push(U.card('四柱与配数',
        U.table(['柱', '干支', '天干', '干数', '地支', '支数'],
          d.rows.map(function (r) {
            return {
              cells: [r.pos, '<span class="mono-k">' + r.gz + '</span>', U.wx(r.gan), r.ganNum, U.wx(r.zhi), r.zhiNum],
              left: [0]
            };
          }).concat([{
            cls: 'hi',
            cells: ['合计', '—', '天数', d.D, '地数', d.E]
          }])) +
        U.note('天干之数依通行口诀「甲己子午九、乙庚丑未八、丙辛寅申七、丁壬卯酉六、戊癸辰戌五、巳亥四」之干数；地支之数用「' + d.zhiWayName + '」（见下方规则全录）。')
      ));

      /* 天数地数 */
      out.push(U.card('天数 · 地数',
        U.kv([
          ['天数（四干之数和）', d.D + '　以二十五取余 → <b>' + d.d + '</b>（' + d.yingTian + '）'],
          ['地数（四支之数和）', d.E + '　以三十取余 → <b>' + d.e + '</b>（' + d.yingDi + '）'],
          ['多寡', d.duoGua === 'tian' ? '天数多于地数：阳刚之气偏胜，其动也显，宜进取、宜外发。'
            : (d.duoGua === 'di' ? '地数多于天数：阴柔之气偏胜，其静也厚，宜守成、宜内修。'
              : '天数地数相当：阴阳相停，宜体用并重、动静得中。')],
          ['取卦之则', '天数为上卦、地数为下卦；先天卦用先天八卦数，后天卦用后天（洛书）八卦数（详见规则全录）。']
        ])));

      /* 卦象 */
      out.push(U.card('先天卦（体 · 本）',
        U.hexBox(d.hexX) +
        U.kv([
          ['卦名', d.hexX.name + '（上' + d.upX + '下' + d.loX + '）'],
          ['取卦之数', '上卦 ' + d.upX + '（天数余 ' + d.d + '，先天数第 ' + (((d.d - 1) % 8) + 1) + '）　下卦 ' + d.loX + '（地数余 ' + d.e + '，先天数第 ' + (((d.e - 1) % 8) + 1) + '）'],
          ['卦义', U.esc(d.hexX.duan)],
          ['先天为体', '体者，本也、己也。此卦示所禀之质与本然之势。']
        ])));

      out.push(U.card('后天卦（用 · 末）',
        U.hexBox(d.hexH) +
        U.kv([
          ['卦名', d.hexH.name + '（上' + d.upH + '下' + d.loH + '）'],
          ['取卦之数', '上卦 ' + d.upH + '（天数余 ' + d.d + '，后天数第 ' + (((d.d - 1) % 9) + 1) + '）　下卦 ' + d.loH + '（地数余 ' + d.e + '，后天数第 ' + (((d.e - 1) % 9) + 1) + '）'],
          ['卦义', U.esc(d.hexH.duan)],
          ['后天为用', '用者，行也、事也。此卦示施为之际与趋向之所归。']
        ]) +
        U.note('后天八卦数之「中五」无卦，本站从遁甲、八宅通例寄坤二宫；若天数余或地数余落于中五，则以后天之坤卦当之。')));

      /* 白话断语 */
      const duan = [];
      duan.push('<b>体（先天卦 ' + d.hexX.name + '）</b>：' + U.esc(d.hexX.duan));
      duan.push('<b>用（后天卦 ' + d.hexH.name + '）</b>：' + U.esc(d.hexH.duan));
      duan.push('<b>数之盈缩</b>：天数 ' + d.D + ' 于二十五为「' + d.yingTian + '」，地数 ' + d.E + ' 于三十为「' + d.yingDi + '」。'
        + (d.yingTian === '盈' && d.yingDi === '不足' ? '天数有余而地数不足：外发有余、根基稍欠，宜借外势而先固其本。'
          : (d.yingTian === '不足' && d.yingDi === '盈' ? '天数不足而地数有余：根基厚而外势欠，宜守内蓄力，待外势自至。'
            : (d.yingTian === '盈' && d.yingDi === '盈' ? '天地之数俱盈：气厚而力足，宜乘时有所作为，然盈则易溢，须留余地。'
              : (d.yingTian === '不足' && d.yingDi === '不足' ? '天地之数俱不足：气薄而力寡，宜收敛节用、循序渐进，不宜大举。'
                : '天地之数有一恰合者，气数得中，宜守常循序，随体用所示而行。')))));
      duan.push('<b>体用合看</b>：体卦（先天）示所禀之质，用卦（后天）示所向之事。二者' +
        (d.hexX.name === d.hexH.name ? '相同，则体用一致，事少反复，宜专一而行；惟亦须防偏执一端。'
          : '不同，则体与用之间有一段路程要走：宜以体卦之质行之用卦之事，勿强以所短逐所求。') +
        '（本卦五行属' + d.hexX.wx + '，用卦五行属' + d.hexH.wx + '，可参' + C.wxRelation(d.hexX.wx, d.hexH.wx) + '之义。）');
      out.push(U.card('白话断语（参考）', U.ul(duan)));

      /* 规则全录 */
      out.push(U.card('配数口诀与取卦规则（全文）', U.ul([
        '<b>配数口诀（通行一路）</b>：甲己子午九、乙庚丑未八、丙辛寅申七、丁壬卯酉六、戊癸辰戌五、巳亥四。',
        '<b>由口诀得天干数</b>：甲九、乙八、丙七、丁六、戊五、己九、庚八、辛七、壬六、癸五。',
        '<b>由口诀得地支数（乙说）</b>：子九、丑八、寅七、卯六、辰五、巳四、午九、未八、申七、酉六、戌五、亥四。',
        '<b>地支洛书宫数（甲说，本站默认）</b>：子一（坎）、丑八（艮）、寅八（艮）、卯三（震）、辰四（巽）、巳四（巽）、午九（离）、未二（坤）、申二（坤）、酉七（兑）、戌六（乾）、亥六（乾）。',
        '<b>第一步 · 定天数地数</b>：取四柱之天干（年干、月干、日干、时干）之数相加，是为「天数」；取四柱之地支（年支、月支、日支、时支）之数相加，是为「地数」。',
        '<b>第二步 · 天数二十五、地数三十</b>：天数以二十五除之，取其余数；地数以三十除之，取其余数。余数为零者，径以二十五、三十当之（即所谓「恰合」）。',
        '<b>第三步 · 先天卦</b>：以天数之余定<b>上卦</b>、地数之余定<b>下卦</b>，按先天八卦数取卦——乾一、兑二、离三、震四、巽五、坎六、艮七、坤八；取数之法为「以八约其余数」（余零作八）。',
        '<b>第四步 · 后天卦</b>：仍以天数之余定上卦、地数之余定下卦，但改按后天（洛书）八卦数取卦——坎一、坤二、震三、巽四、中五（寄坤）、乾六、兑七、艮八、离九；取数之法为「以九约其余数」（余零作九）。',
        '<b>第五步 · 合成六爻卦</b>：下卦在下、上卦在上，合为六十四卦之一，即先天卦与后天卦。'
      ])));

      out.push(U.note('异说与简化之声明：① 干支配数古今异说颇多——有以河图生成数配天干者，有以纳音五行之数配干支者，亦有径以五行生数（水一、火二、木三、金四、土五）配四柱者，名目不一；本站所列口诀为通行一路，地支之数另备洛书宫数一说，二者可择，此处不作定论。② 本站「天数」取四干之数和、「地数」取四支之数和；另有以日干、日支为主而余为宾之说，本站从简，不取。③ <b>先天卦、后天卦的取卦法为本站所定之简化</b>：原书取先天、后天卦的细节（涉及爻位、纳甲、大运卦、流年卦、命卦与运卦之分等）本站未采用，只以「先天数取先天卦、后天数取后天卦」为则。④ 「后天卦即用、先天卦即体」为本站为便于解说所立之义，非原书明文。', true));

      /* 术语 */
      out.push(U.card('术语小释', U.kv([
        ['河图之数', '一六水、二七火、三八木、四九金、五十土，即五行之生数与成数；本页「天干配河图数」即承此一路以数配干支之说（异说见上方声明）。'],
        ['洛书之数', '戴九履一、左三右七、二四为肩、六八为足，布于九宫；本页「地支洛书宫数」「后天八卦数」皆出此。'],
        ['天数二十五 · 地数三十', '天数为阳数之总、地数为阴数之总；取其数以为取卦之则，过之则去其倍数而用其余。'],
        ['化卦', '把干支之数转为卦象的整个过程，即「以数化卦」。'],
        ['先天卦 · 后天卦', '本站以先天八卦数所取者为先天卦（体）、以后天八卦数所取者为后天卦（用）。'],
        ['体 · 用', '体指本然之质、己身；用指施为之事、趋向。体用合看，即「以何质行何事」。'],
        ['四柱', '年、月、日、时四组干支，共八字，故八字亦称四柱。本页四柱由干支历引擎依节气与时辰推算。']
      ])));

      out.push(U.note('本站自述：四柱由本站干支历引擎依节气（年以立春为界、月以十二节为界、日以二十三时换日）推算；配数口诀与取卦规则已全文列于上，读者可自行验算。断语为参考白话，非原书断法。', true));

      out.push(U.disclaim('河洛化卦所求者，不过是把「禀气之厚薄」与「施为所向」摆在两处对照着看；数有盈缩，人事有进退，取舍仍在于己。'));
      return out.join('');
    }
  });
})();
