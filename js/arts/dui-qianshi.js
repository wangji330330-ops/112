  /* 取签：同一输入必得同一签（纯函数） */
  function drawSign(set, shakes) {
    const n = POOL.length;                 /* 49 项（48 签 + 签王） */
    const idx = (((shakes - 1) * (set.step || 1) + (set.offset || 0)) % n + n) % n;
    /* 签王居末位：仅当 idx 恰落在签王上才出签王（概率 1/49，与签筒中签王之设相当） */
    const inRange = idx < (set.sticks || 48);
    const stickIdx = set.reverse ? ((set.sticks || 48) - 1 - (idx % (set.sticks || 48))) : (idx % (set.sticks || 48));
    const item = inRange ? POOL[stickIdx] : POOL[n - 1];
    const total = set.sticks || 48;
    /* 签筒抽出的第几支（0 基），喂给 U.qian(total, pulled) */
    const pulled = item.no === '签王' ? (set.reverse ? 0 : total - 1) : (item.no - 1);
    return { item, total, pulled, tip: inRange ? null : '签王' };
  }

